import assert from 'node:assert/strict';
import test from 'node:test';
import { JSDOM } from 'jsdom';
import ORIGIN_BYTES from '../fixtures/descriptive-report-origin.json' with { type: 'json' };
import { buildDescriptiveMarketMethods, verifyDescriptiveMarketMethods } from '../../src/modules/analysis/descriptive-market-methods.js';
import { describeDescriptiveSection, type DescriptiveReaderContext, type DescriptiveSectionId } from '../../src/modules/analysis/research-automation/descriptive-report.js';
import { descriptiveReaderFixture } from '../helpers/descriptive-reader-fixture.js';

const ids: DescriptiveSectionId[] = ['M05', 'M06', 'M07', 'M09'];
const citations = { mark: () => '[1]' };
const context: DescriptiveReaderContext = {
  productLabels: new Map([['synthetic:product-a', 'Bình nhỏ'], ['synthetic:product-b', 'Bình lớn']]),
  requestedPeriod: { startDate: '2026-01-01', endDate: '2026-02-28' },
};
type Methods = ReturnType<typeof descriptiveReaderFixture>;
function rebuild(methods: Methods, changes: Partial<Methods['input']>): Methods {
  return buildDescriptiveMarketMethods({ ...methods.input, ...changes }, { methodVersion: methods.methodVersion as '1.0.0' | '1.1.0' }).output;
}
function reader(methods: Methods, id: DescriptiveSectionId, displayContext = context) {
  const view = describeDescriptiveSection(methods, id, citations, true, displayContext);
  const document = new JSDOM(view.html).window.document;
  return { ...view, document, text: document.body.textContent ?? '' };
}

test('reader coverage names only non-empty counts and keeps technical coverage unchanged', () => {
  const methods = descriptiveReaderFixture();
  const base = methods.input.m05[0]!;
  const rows = ['observed_value', 'observed_zero', 'missing', 'UNKNOWN'].map((state, index) => ({ ...base,
    source: { ...base.source, locator: `/coverage/${index}` },
    observation: { state: state as typeof base.observation.state, value: index === 0 ? '12' : index === 1 ? '0' : null, precision: 'exact' as const } }));
  const changed = rebuild(methods, { m05: rows });
  const text = reader(changed, 'M05').text;
  assert.match(text, /2 dòng có số; 1 dòng bằng không; 1 dòng thiếu số; 1 dòng chưa rõ\./u);
  assert.doesNotMatch(text, /Không chính xác|\b0\b/u);
  const technical = describeDescriptiveSection(changed, 'M05', citations).html;
  assert.match(technical, /Có số 2 · Bằng 0 1 · Thiếu 1 · UNKNOWN 1 · Không chính xác 0/u);
  assert.match(reader(rebuild(methods, { m05: rows.slice(0, 1) }), 'M05').text, /Mọi dòng đều có số\./u);
});

// Exact HTML bytes generated by importing a temporary copy of descriptive-report.ts
// from origin/main 918db40ebf5a6e27ada4142ebda17697220d115c, before any renderer edits.
test('all descriptive sections preserve origin/main legacy bytes, including explicit false and reader context', () => {
  for (const version of ['1.0.0', '1.1.0'] as const) {
    const methods = descriptiveReaderFixture(version);
    for (const id of ids) {
      const expected = ORIGIN_BYTES[`${version}:${id}` as keyof typeof ORIGIN_BYTES];
      assert.equal(describeDescriptiveSection(methods, id, citations).html, expected);
      assert.equal(describeDescriptiveSection(methods, id, citations, false, context).html, expected);
      reader(methods, id);
      assert.equal(describeDescriptiveSection(methods, id, citations).html, expected, 'reader state must not leak');
    }
    assert.equal(describeDescriptiveSection(methods, 'M06', { ...citations, distinctEntityWording: true }, false).html,
      ORIGIN_BYTES[`${version}:M06:distinct`]);
  }
});

