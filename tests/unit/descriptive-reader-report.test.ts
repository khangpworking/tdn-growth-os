test('M05 preserves conflicting or separate-source values instead of overwriting, joining or summing them', () => {
  const methods = descriptiveReaderFixture();
  const first = methods.input.m05[0]!;
  const changed = rebuild(methods, { m05: [first,
    { ...first, source: { ...first.source, locator: '/observations/duplicate' }, observation: { ...first.observation, state: 'observed_value', value: '25' } },
    { ...first, source: { sourceSha256: methods.input.sources[1]!.sha256, locator: '/observations/other-source' },
      observation: { ...first.observation, state: 'observed_value', value: '19' } },
  ] });
  const view = reader(changed, 'M05');
  assert.equal(view.document.querySelectorAll('table').length, 1);
  assert.equal(view.document.querySelectorAll('tbody tr').length, 2, 'same title cannot join separate sources');
  assert.match(view.text, /Không ghi nhận/);
  assert.match(view.text, /25/);
  assert.match(view.text, /19/);
  assert.doesNotMatch(view.text, /44/);
  assert.equal(view.text.match(/\[1\]/g)?.length, 3, 'each retained observation keeps its own citation');
});

test('M05 merges twenty-six observation groups and keeps missing and unknown distinct from observed zero', () => {
  const methods = descriptiveReaderFixture();
  const observations = Array.from({ length: 13 }, (_, month) => methods.input.m05.filter(row => row.period!.start === '2026-01-01').map((row, index) => {
    const start = month === 12 ? '2026-01-01' : `2025-${String(month + 1).padStart(2, '0')}-01`;
    return { ...row, source: { ...row.source, locator: `/observations/month-${month}-${index}` }, period: { ...row.period!, start, end: start } };
  })).flat();
  observations[1]!.observation = { state: 'missing', value: null, precision: 'exact' };
  observations[3]!.observation = { state: 'UNKNOWN', value: null, precision: 'exact' };
  const changed = rebuild(methods, { m05: observations });
  assert.equal(changed.sections.M05.partitions.length, 26);
  const view = reader(changed, 'M05');
  assert.equal(view.document.querySelectorAll('table').length, 2);
  assert.equal(view.document.querySelectorAll('tbody tr').length, 4);
  assert.equal(view.document.querySelector('thead')!.querySelectorAll('th').length, 14);
  assert.match(view.text, /Chưa có dữ liệu/);
  assert.match(view.text, /Chưa rõ/);
  assert.match(view.text, /Không ghi nhận/);
  assert.doesNotMatch(view.text, /\b0\b|UNKNOWN|Tổng năm|toàn thị trường/);
});

